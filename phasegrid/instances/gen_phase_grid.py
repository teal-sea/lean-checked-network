"""Write a phase-grid network (p, S, M) into the core-Lean package, one theorem per row, as gen_lean.py does.

Usage: python3 gen_phase_grid.py P M NAME CHUNKS [k1,k2,...]
  S defaults to all frequencies 1..(p-1)//2.  Tables: e = round(M cos(2 pi k x / p + phase)), round half up.
Checks in numpy (exact int64) that the network is right on every pair before writing anything.
"""
import sys
from pathlib import Path
import numpy as np

_argv = list(sys.argv[1:])
if "--bchunks" in _argv:
    _i = _argv.index("--bchunks"); del _argv[_i:_i + 2]
args = [a for a in _argv if not a.startswith("--")]
p, M, name, chunks = int(args[0]), int(args[1]), args[2], int(args[3])
S = [int(k) for k in args[4].split(",")] if len(args) > 4 else list(range(1, (p-1)//2 + 1))
root = Path(__file__).resolve().parent / "phasegrid-instances" / "PhaseGridInstances" / name
root.mkdir(parents=True, exist_ok=True)

GRID = [(j, l) for j in range(4) for l in range(2)]   # phi1 = j pi/2, phi2 = l pi/2, the order of PhaseGrid.grid
x = np.arange(p)
c1, c2, cw = [], [], []
for k in S:
    for j, l in GRID:
        c1.append(M*np.cos(2*np.pi*k*x/p + j*np.pi/2))
        c2.append(M*np.cos(2*np.pi*k*x/p + l*np.pi/2))
        cw.append(M*np.cos(2*np.pi*k*x/p + (j + l)*np.pi/2))
reals = [np.array(c).T for c in (c1, c2, cw)]
half_dist = min(np.abs((r + 0.5) - np.round(r + 0.5)).min() for r in reals)
assert half_dist > 1e-9, f"a weight is within {half_dist:.1e} of a half-integer; rounding would be ambiguous"
E1, E2, W2 = (np.floor(r + 0.5).astype(np.int64) for r in reals)
H = 8*len(S)
assert E1.shape == (p, H) and np.abs(W2).max() <= 127 and np.abs(E1).max() <= M

# exact numpy check of every pair, with the first-index argmax of Network.lean
U = (E1*E1) @ W2.T; V = (E2*E2) @ W2.T
wrong = 0; margin = None; ties = 0
for a in range(p):
    I = U[a][None, :] + V + 2*((E1[a]*E2) @ W2.T)
    tgt = (a + np.arange(p)) % p
    wrong += int((I.argmax(1) != tgt).sum())
    best = I[np.arange(p), tgt]; I2 = I.copy(); I2[np.arange(p), tgt] = np.iinfo(np.int64).min
    other = I2.max(1); ties += int((other == best).sum())
    m = int((best - other).min()); margin = m if margin is None else min(margin, m)
hmax = int(((E1[:, None, :] + E2[None, :, :])**2).sum(2).max()) if p*p*H < 2e8 else int((2*M)**2 * H)
print(f"{name}: p={p} |S|={len(S)} H={H} M={M} |w|max={np.abs(W2).max()} wrong={wrong} ties={ties} min margin={margin} "
      f"half-int dist={half_dist:.1e} 255*max(sum h)={255*hmax} < 2^32={255*hmax < 2**32}")
assert wrong == 0 and ties == 0 and 255*hmax < 2**32
np.savez(root / f"{name}.npz", p=p, H=H, M=M, S=np.array(S), E1q=E1, E2q=E2, W2q=W2)

def lit(v):
    v = int(v)
    return f"(.ofNat {v})" if v >= 0 else f"(.negSucc {-v - 1})"
def table(m):
    return "[\n" + ",\n".join("  [" + ", ".join(lit(v) for v in row) + "]" for row in m) + "]"

# --rowdefs: write each table as one definition per row plus a list of the row names. One literal of
# p * H entries is elaborated as a single term; at 113 x 448 = 50,624 entries that exhausted the memory
# of the elaborator (Lean killed with exit code 137 after 369 s), while a 448-entry row is small.
ROWDEFS = "--rowdefs" in sys.argv
def table_defs(nm, m):
    if not ROWDEFS:
        return f"def {nm} : List (List Int) := {table(m)}"
    rows = "\n\n".join(f"def {nm}_{i} : List Int := [" + ", ".join(lit(v) for v in row) + "]" for i, row in enumerate(m))
    return rows + f"\n\ndef {nm} : List (List Int) := [" + ", ".join(f"{nm}_{i}" for i in range(len(m))) + "]"

desc = f"the phase-grid network at p = {p}, frequencies {S if len(S) <= 8 else f'1 to {S[-1]}'}, scale M = {M}"
(root / "Weights.lean").write_text(f"""import PhaseGridInstances.Network

/-!
# Weights of {desc}

{p} inputs per side, {H} neurons: for each frequency k in S, eight neurons with phases
phi1 in {{0, pi/2, pi, 3pi/2}} and phi2 in {{0, pi/2}}. Entry [x][h] of E1 is round({M} cos(2 pi k x / {p} + phi1)),
of E2 is round({M} cos(2 pi k x / {p} + phi2)), of W2 is round({M} cos(2 pi k x / {p} + phi1 + phi2)), round half up.
`.ofNat n` is the integer n and `.negSucc n` is the integer -(n + 1). Generated by `gen_phase_grid.py`.
-/

set_option maxRecDepth 100000
set_option maxHeartbeats 0  -- elaboration time limit only (not a soundness option); the 113 x 448 tables exceed the default 200000

namespace PhaseGridInstances.{name}

{table_defs('E1', E1)}

{table_defs('E2', E2)}

{table_defs('W2', W2)}

/-- The network's answer for the pair `(a, b)`. -/
def answer (a b : Nat) : Nat := LeanCheckedNetwork.answer E1 E2 W2 a b

end PhaseGridInstances.{name}
""")
(root / "Table.lean").write_text(f"""import PhaseGridInstances.Fast
import PhaseGridInstances.{name}.Weights

namespace PhaseGridInstances.{name}

open LeanCheckedNetwork

/-- Every read-out row has {H} entries, each in [-128, 127]: the condition the fast evaluator needs. -/
theorem table_ok : tableOk W2 {H} = true := by decide +kernel

end PhaseGridInstances.{name}
""")
# --bchunks N: split each row's check over b into N consecutive ranges, one `decide +kernel` per range. The
# kernel frees its caches between declarations, so the peak memory of one row file drops by about N
# (at p = 113 with 448 neurons one row's single `decide` needed 4.3 to 5.8 GB and was OOM-killed).
BCH = int(sys.argv[sys.argv.index("--bchunks") + 1]) if "--bchunks" in sys.argv else 1
bounds = [int(v) for v in np.linspace(0, p, BCH + 1).round()]
for i, rs in enumerate(np.array_split(np.arange(p), chunks)):
    body = []
    for a in rs:
        a = int(a)
        if BCH == 1:
            body.append(f"""theorem fast_{a} : ∀ b, b < {p} →
    (fastOk E1 E2 {H} {a} b && fastAnswer E1 E2 W2 {H} {a} b == ({a} + b) % {p}) = true := by
  decide +kernel

/-- Row {a} of the addition table: the network answers ({a} + b) % {p} for every b. -/
theorem row_{a} : ∀ b, b < {p} → answer {a} b = ({a} + b) % {p} := by
  intro b hb
  have h := fast_{a} b hb
  simp only [Bool.and_eq_true, beq_iff_eq] at h
  show LeanCheckedNetwork.answer E1 E2 W2 {a} b = _
  rw [answer_eq_fastAnswer E1 E2 W2 {H} {a} b table_ok h.1, h.2]
""")
        else:
            for c in range(BCH):
                lo, hi = bounds[c], bounds[c + 1]
                body.append(f"""theorem fast_{a}_{c} : ∀ b, b < {hi - lo} →
    (fastOk E1 E2 {H} {a} ({lo} + b) && fastAnswer E1 E2 W2 {H} {a} ({lo} + b) == ({a} + ({lo} + b)) % {p}) = true := by
  decide +kernel
""")
            steps = []
            for c in range(BCH):
                lo, hi = bounds[c], bounds[c + 1]
                use = f"have h := fast_{a}_{c} (b - {lo}) (by omega); rwa [show {lo} + (b - {lo}) = b by omega] at h"
                if c < BCH - 1:
                    steps.append(f"    rcases Nat.lt_or_ge b {hi} with h{c} | h{c}\n    · {use}")
                else:
                    steps.append(f"    {use}")
            body.append(f"""/-- Row {a} of the addition table: the network answers ({a} + b) % {p} for every b. -/
theorem row_{a} : ∀ b, b < {p} → answer {a} b = ({a} + b) % {p} := by
  intro b hb
  have key : (fastOk E1 E2 {H} {a} b && fastAnswer E1 E2 W2 {H} {a} b == ({a} + b) % {p}) = true := by
{chr(10).join(steps)}
  simp only [Bool.and_eq_true, beq_iff_eq] at key
  show LeanCheckedNetwork.answer E1 E2 W2 {a} b = _
  rw [answer_eq_fastAnswer E1 E2 W2 {H} {a} b table_ok key.1, key.2]
""")
    (root / f"Rows{i:02d}.lean").write_text(f"""import PhaseGridInstances.{name}.Table

/-! Rows {int(rs[0])} to {int(rs[-1])} of the addition table, checked by Lean's kernel for all {p} values of `b`. -/

set_option Elab.async false

namespace PhaseGridInstances.{name}

open LeanCheckedNetwork

{chr(10).join(body)}
end PhaseGridInstances.{name}
""")
cases = "\n".join(f"  | {a}, _ => exact row_{a}" for a in range(p))
imports = "\n".join(f"import PhaseGridInstances.{name}.Rows{i:02d}" for i in range(chunks))
(root / "AllInputs.lean").write_text(f"""{imports}

/-!
# {desc[0].upper() + desc[1:]}: right on every input

The network answers `(a + b) % {p}` for all {p * p} pairs `(a, b)`.
-/

namespace PhaseGridInstances.{name}

theorem adds_mod_{p} : ∀ a, a < {p} → ∀ b, b < {p} → answer a b = (a + b) % {p} := by
  intro a ha
  match a, ha with
{cases}
  | n + {p}, h => exact absurd h (by omega)

end PhaseGridInstances.{name}
""")
print(f"wrote {root}: {chunks} row files")
