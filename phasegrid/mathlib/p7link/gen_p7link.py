"""Generate PhaseGrid/P7Link.lean: the stage 3 tables at p = 7 (P7FullTables) are within 1/2 of 25 times the
analytic weights, so the general theorem adds_mod_p_tables proves them right on every pair.

Certified values: y = pi/28 with pi in (3.141592, 3.141593) (Real.pi_gt_d6, pi_lt_d6), Real.cos_bound and
Real.sin_bound at y, then three doublings. The rational constants are computed here with exact fractions,
rounded outward to 10 decimals, and checked against every table entry before the Lean file is written.
Usage: python3 gen_p7link.py [--test]   (--test writes only a few entries, to check the goal shapes)
"""
import sys, math
from fractions import Fraction as F
import numpy as np

TEST = "--test" in sys.argv
PI_LO, PI_HI = F(3141592, 10**6), F(3141593, 10**6)
D = 10**10
def out_lo(x): return F(math.floor(x * D), D)
def out_hi(x): return F(math.ceil(x * D), D)
def interval_mul(a, b):
    c = [a[0]*b[0], a[0]*b[1], a[1]*b[0], a[1]*b[1]]; return (min(c), max(c))
def sq(a): assert a[0] >= 0; return (a[0]**2, a[1]**2)
def lean_rat(q):
    return f"({q.numerator} / {q.denominator} : ℝ)" if q.denominator != 1 else f"({q.numerator} : ℝ)"

y = (PI_LO/28, PI_HI/28)
y2, y4 = sq(y), sq(sq(y)); y3 = interval_mul(y2, y); y5 = interval_mul(y4, y)
ec, es = y4[1]*F(5, 96), y5[1]/100
cos_y = (out_lo(1 - y2[1]/2 - ec), out_hi(1 - y2[0]/2 + ec))
sin_y = (out_lo(y[0] - y3[1]/6 - es), out_hi(y[1] - y3[0]/6 + es))
def double(c, s):
    s2, sc = sq(s), interval_mul(s, c)
    return (out_lo(1 - 2*s2[1]), out_hi(1 - 2*s2[0])), (out_lo(2*sc[0]), out_hi(2*sc[1]))
c28, s28 = cos_y, sin_y
c14, s14 = double(c28, s28)
c7, s7 = double(c14, s14)
c27, s27 = double(c7, s7)          # 2 pi / 7
c47, s47 = double(c27, s27)        # 4 pi / 7 (cos negative)
# canonical values v_r = (cos, sin) of 2 pi r / 7, r = 1, 2, 3
V = {1: (c27, s27), 2: (c47, s47), 3: ((-c7[1], -c7[0]), s7)}
for r in (1, 2, 3):
    tc, ts = F(np.cos(2*np.pi*r/7)), F(np.sin(2*np.pi*r/7))
    assert V[r][0][0] <= tc <= V[r][0][1] and V[r][1][0] <= ts <= V[r][1][1]

# the tables, exactly as gen_phase_grid.py writes them (round half up of 25 cos, in double precision)
M, p, S = 25, 7, [1, 2, 3]
GRID = [(j, l) for j in range(4) for l in range(2)]
def entry(k, x, ph):
    return int(np.floor(M*np.cos(2*np.pi*k*x/p + ph*np.pi/2) + 0.5))
def box(r, q):
    """rational box for cos(2 pi r/7 + q pi/2), r in 0..6, q in 0..3, and the canonical description"""
    r %= 7; q %= 4
    neg = lambda a: (-a[1], -a[0])
    if r == 0: cb, sb = (F(1), F(1)), (F(0), F(0))
    elif r <= 3: cb, sb = V[r]
    else: cb, sb = V[7 - r][0], neg(V[7 - r][1])
    return [cb, neg(sb), neg(cb), sb][q]
# check every entry against its box
worst = F(0)
for k in S:
    for j, l in GRID:
        for x in range(p):
            for ph in (j, l, j + l):
                lo, hi = box(k*x, ph); t = entry(k, x, ph)
                d = max(abs(t - M*lo), abs(t - M*hi)); worst = max(worst, d)
                assert d <= F(1, 2)
print(f"all 504 entries within 1/2 of 25 * box: worst {float(worst):.6f}")

