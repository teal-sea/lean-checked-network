"""Negative control for a sealed package: doctor one fact and check that `lake build` fails.

Usage: python3 seal_negative_control.py SEAL_DIR OUT_DIR [--build-jobs N]

SEAL_DIR is one of seals/<cell> (holds lean/ as generated by seal_cell.py). For each doctoring
below a copy of the package is built; the control passes only if every doctored copy FAILS to
build and an undoctored copy builds. Doctorings:

  drop_pair     remove the first listed wrong pair of the Trained network from wrongRows and
                wrongPairs (and lower wrongPairs_length by one), so the row theorem for that row
                states the network is right on a pair it is wrong on;
  energy_bound  lower the stated per-mille bound of energy_E1 by one below the measured value
                (seal_cell.py states the measured value rounded up, so one less must fail when
                the measured value is not an integer per mille; if it is, lower by two);
  extra_entry   change one entry of the reduction's extra E1 column from 127 to 126, so extra_E1
                must fail (and the row theorems of ClockBias for that row may fail too);
  shape         state the wrong number of bias neurons in shape_E1.

Each copy is built with the same lakefile and toolchain as the seal. The result is written to
OUT_DIR/result.json: for each doctoring, the build exit code, whether "error" appeared in the
log, and the verdict. Nothing here changes the sealed package."""
import argparse, json, os, re, shutil, subprocess, sys, time
from pathlib import Path


def run(cmd, cwd, env, log):
    t0 = time.time()
    with open(log, "w") as fh:
        r = subprocess.run(cmd, cwd=cwd, env=env, stdout=fh, stderr=subprocess.STDOUT, text=True)
    return r.returncode, time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("seal_dir"); ap.add_argument("out_dir")
    ap.add_argument("--build-jobs", type=int, default=0)
    args = ap.parse_args()
    seal = Path(args.seal_dir).resolve(); out = Path(args.out_dir).resolve(); out.mkdir(parents=True, exist_ok=True)
    src = seal / "lean"
    env = dict(os.environ); env["PATH"] = str(Path.home() / ".elan" / "bin") + os.pathsep + env.get("PATH", "")
    if args.build_jobs: env["LEAN_NUM_THREADS"] = str(args.build_jobs)
    seal_root = next((src / "LeanCheckedNetwork" / "Seal").iterdir())
    lib = f"LeanCheckedNetwork.Seal.{seal_root.name}"
    result = {"seal": str(seal), "lib": lib, "controls": {}}

    def fresh(name):
        d = out / name
        if d.exists(): shutil.rmtree(d)
        shutil.copytree(src, d, ignore=shutil.ignore_patterns(".lake"))
        return d

    def doctor_drop_pair(d):
        w = d / "LeanCheckedNetwork" / "Seal" / seal_root.name / "Trained" / "Weights.lean"
        t = w.read_text()
        m = re.search(r"def wrongPairs : List \(Nat × Nat\) := \[\((\d+), (\d+)\)", t)
        if not m: return "no wrong pair to drop (network right on every pair)"
        a, b = m.group(1), m.group(2)
        t = t.replace(f"def wrongPairs : List (Nat × Nat) := [({a}, {b}), ", "def wrongPairs : List (Nat × Nat) := [", 1) \
            if f"[({a}, {b}), " in t else t.replace(f"def wrongPairs : List (Nat × Nat) := [({a}, {b})]", "def wrongPairs : List (Nat × Nat) := []", 1)
        # the row list: row a is the (a+1)-th bracket after "def wrongRows"
        i = t.index("def wrongRows"); rows = t[i:].split("\n")
        row_line = rows[1 + int(a)]
        new_row = re.sub(rf"\[{b}(, |\])", lambda mm: "[" if mm.group(1) == ", " else "[]", row_line, count=1)
        rows[1 + int(a)] = new_row
        t = t[:i] + "\n".join(rows)
        t = re.sub(r"(\d+) pairs in all", lambda mm: f"{int(mm.group(1)) - 1} pairs in all", t, count=1)
        w.write_text(t)
        tb = d / "LeanCheckedNetwork" / "Seal" / seal_root.name / "Trained" / "Table.lean"
        s = tb.read_text(); s = re.sub(r"wrongPairs\.length = (\d+)", lambda mm: f"wrongPairs.length = {int(mm.group(1)) - 1}", s); tb.write_text(s)
        return f"dropped ({a}, {b})"

    def doctor_energy(d):
        br = d / "LeanCheckedNetwork" / "Seal" / seal_root.name / "Bridge.lean"
        s = br.read_text()
        m = re.search(r"energyWithin Trained\.E1 ClockBias\.E1 (\d+) (\d+) 1000", s)
        H, permille = m.group(1), int(m.group(2))
        meas = json.load(open(seal / "result.json"))["reduction"]["energy_outside_wave"][0] * 1000
        new = permille - 1 if permille - 1 < meas else permille - 2
        s = s.replace(f"energyWithin Trained.E1 ClockBias.E1 {H} {permille} 1000", f"energyWithin Trained.E1 ClockBias.E1 {H} {new} 1000")
        br.write_text(s)
        return f"energy_E1 bound {permille} -> {new} per mille (measured {meas:.2f})"

    def doctor_extra(d):
        w = d / "LeanCheckedNetwork" / "Seal" / seal_root.name / "ClockBias" / "Weights.lean"
        t = w.read_text()
        i = t.index("def E1 : List (List Int)")
        j = t.index("(.ofNat 127)]", i)   # last entry of the first row is an extra column (= 127)
        t = t[:j] + "(.ofNat 126)]" + t[j + len("(.ofNat 127)]"):]
        w.write_text(t)
        return "ClockBias.E1 row 0 last extra entry 127 -> 126"

    def doctor_shape(d):
        br = d / "LeanCheckedNetwork" / "Seal" / seal_root.name / "Bridge.lean"
        s = br.read_text()
        m = re.search(r"shapeOk Trained\.E1 ClockBias\.E1 (\d+) (\d+) (\d+)", s)
        p, H, n = m.groups()
        s = s.replace(f"shapeOk Trained.E1 ClockBias.E1 {p} {H} {n}", f"shapeOk Trained.E1 ClockBias.E1 {p} {H} {int(n) + 1}")
        br.write_text(s)
        return f"shape_E1 bias neurons {n} -> {int(n) + 1}"

    plan = [("positive", None), ("drop_pair", doctor_drop_pair), ("energy_bound", doctor_energy), ("extra_entry", doctor_extra), ("shape", doctor_shape)]
    for name, fn in plan:
        d = fresh(name)
        note = fn(d) if fn else "undoctored copy"
        rc, dt = run(["lake", "build", "LeanCheckedNetwork"], d, env, out / f"build.{name}.log")
        log = (out / f"build.{name}.log").read_text()
        built = rc == 0 and "Build completed successfully" in log
        errors = [l for l in log.splitlines() if "error" in l][:5]
        expect_fail = fn is not None
        ok = (not built) if expect_fail else built
        result["controls"][name] = {"note": note, "exit": rc, "built": built, "seconds": round(dt, 1), "errors": errors, "as_expected": ok}
        print(name, "|", note, "| built", built, "| as expected", ok, f"| {dt:.0f}s", flush=True)
        (out / "result.json").write_text(json.dumps(result, indent=1))
        shutil.rmtree(d / ".lake", ignore_errors=True)
    result["ok"] = all(c["as_expected"] for c in result["controls"].values())
    (out / "result.json").write_text(json.dumps(result, indent=1))
    print("negative control", "OK" if result["ok"] else "FAILED")
    sys.exit(0 if result["ok"] else 1)


if __name__ == "__main__":
    main()
