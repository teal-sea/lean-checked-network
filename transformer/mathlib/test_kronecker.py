def small_data(seed=1):
    """A deterministic integer data set with the production shapes (no real weights)."""
    x = seed

    def nxt(lo, hi):
        nonlocal x
        x = (1103515245 * x + 12345) % 2 ** 31
        return lo + x % (hi - lo + 1)
    return {
        'tok': [[nxt(-60, 60) for _ in range(128)] for _ in range(114)],
        'pos': [[nxt(-50, 50) for _ in range(128)] for _ in range(3)],
        'WV': [[nxt(-90, 90) for _ in range(128)] for _ in range(128)],
        'WO': [[nxt(-90, 90) for _ in range(32)] for _ in range(512)],
        'Win': [[nxt(-80, 80) for _ in range(128)] for _ in range(512)],
        'U': [[nxt(-30, 30) for _ in range(128)] for _ in range(113)],
    }


def declarations(text):
    """Fully qualified theorem/def names, tracking namespace and section scopes."""
    stack, out = [], []
    for line in text.splitlines():
        m = re.match(r'^namespace (\S+)\s*$', line)
        if m:
            stack.append(('ns', m.group(1)))
            continue
        m = re.match(r'^(?:noncomputable )?section(?: (\S+))?\s*$', line)
        if m:
            stack.append(('sec', m.group(1)))
            continue
        m = re.match(r'^end(?: (\S+))?\s*$', line)
        if m:
            kind, name = stack.pop()
            assert (m.group(1) or None) == (name or None)
            continue
        m = re.match(r'^(theorem|def) (\S+)', line)
        if m:
            out.append('.'.join([n for k, n in stack if k == 'ns'] + [m.group(2)]))
    assert not stack
    return out


class Bounds(unittest.TestCase):
    def test_bounds_are_maxima_of_the_slices_read(self):
        d = small_data()
        for h in range(4):
            for field, mat in (('TI', 'Win'), ('TU', 'U')):
                P = kg.params(d, h, field)
                self.assertEqual(P['Kt'], max(abs(v) for r in d['tok'] for v in r))
                self.assertEqual(P['Kv'], max(abs(v) for r in d['WV'][32 * h:32 * h + 32] for v in r))
                self.assertEqual(P['Ko'], max(abs(v) for r in d['WO'][128 * h:128 * h + 128] for v in r))
                self.assertEqual(P['Kw'], max(abs(v) for r in d[mat] for v in r))

    def test_inequalities_checked_by_the_kernel_hold(self):
        d = small_data(7)
        for h in range(4):
            for field in ('TI', 'TU'):
                P = kg.params(d, h, field)
                crude = 128 * P['Kw'] * 32 * P['Ko'] * 128 * (P['Kt'] + P['Kp']) * P['Kv']
                self.assertLessEqual(crude, P['K'])
                self.assertLess(2 * P['K'], P['B'])
                self.assertEqual(P['B'], 2 ** P['k'])
                self.assertGreaterEqual(2 * P['K'], P['B'] // 2, 'B is the smallest power of two above 2K')

    def test_base_exponent_edge_cases(self):
        # Smallest power of two strictly above 2K, never below the kernel's floor B >= 2.
        self.assertEqual([kg.base_exponent(K) for K in (0, 1, 2, 3, 4)], [1, 2, 3, 3, 4])
        for K in range(0, 300):
            B = 2 ** kg.base_exponent(K)
            self.assertTrue(2 * K < B and 2 <= B)
            self.assertTrue(B == 2 or 2 * K >= B // 2, f'B not minimal for K={K}')

    def test_bound_is_sound_for_the_true_values(self):
        d = small_data(3)
        P = kg.params(d, 0, 'TU')
        o = kg.ovec(d, 0, 4, 1)
        for k in range(0, 113, 17):
            val = sum(o[e] * d['U'][k][e] for e in range(128))
            self.assertLessEqual(abs(val), P['K'])


class Emission(unittest.TestCase):
    def setUp(self):
        self.files, self.table = kg.emit(small_data())

    def test_module_inventory(self):
        heads = sorted(f'TransformerBridge/Kronecker/Heads/{p}{f}{h}.lean'
                       for p in ('Check', '') for f in ('TI', 'TU') for h in range(4))
        self.assertEqual(sorted(self.files), sorted(heads + ['TransformerBridge/Kronecker/Fields.lean']))
        self.assertEqual(len(self.files), 17)

    def test_header_and_options(self):
        for rel, text in self.files.items():
            self.assertTrue(text.startswith('-- Generated by transformer/mathlib/kronecker_generate.py.'), rel)
            self.assertIn('set_option autoImplicit false', text)
            self.assertNotIn('maxRecDepth', text)
            self.assertNotIn('maxHeartbeats', text)

    def test_check_modules_have_one_kernel_decide(self):
        for h in range(4):
            for f, mat, n in (('TI', 'Win', 512), ('TU', 'U', 113)):
                text = self.files[f'TransformerBridge/Kronecker/Heads/Check{f}{h}.lean']
                self.assertEqual(text.count('decide +kernel'), 1)
                self.assertEqual(declarations(text), [f'TransformerBridge.Kronecker.Heads.check{f}{h}'])
                P = self.table[f'{f}{h}']
                self.assertIn(f'headCheck {P["B"]} {P["K"]} {P["Kt"]} {P["Kp"]} {P["Kv"]} {P["Ko"]} {P["Kw"]} {n} {h}\n',
                              text)
                self.assertIn(f'Data.{mat}\n', text)
                for j in range(3):
                    self.assertIn(f'TransformerCore.Net.tab.{f}{j} {h})', text)
                self.assertIn(f'import TransformerBridge.RawPacked.Generated.{mat}\n', text)

    def test_head_modules_state_the_table_equality(self):
        for h in range(4):
            for f in ('TI', 'TU'):
                text = self.files[f'TransformerBridge/Kronecker/Heads/{f}{h}.lean']
                self.assertNotIn('decide', text)
                self.assertEqual(declarations(text), [f'TransformerBridge.Kronecker.Heads.{f}_head{h}',
                                                      f'TransformerBridge.Kronecker.Heads.{f}_head{h}_eq'])
                self.assertIn(f'(toTables TransformerCore.Net.tab).{f} {h} = (weights.rawTables 256).{f} {h}', text)
                self.assertIn(f'{f}_head_of_check weights S', text)
                self.assertEqual(text.count('(fun _ _ => rfl)'), 5)

    def test_fields_module(self):
        text = self.files['TransformerBridge/Kronecker/Fields.lean']
        self.assertEqual(declarations(text), ['TransformerBridge.Kronecker.TI_eq', 'TransformerBridge.Kronecker.TU_eq'])
        for f in ('TI', 'TU'):
            self.assertIn(f'theorem {f}_eq :\n    (toTables TransformerCore.Net.tab).{f} = '
                          f'(TransformerBridge.RawPackedPilot.weights.rawTables 256).{f} := by', text)
            for h in range(4):
                self.assertIn(f'exact Heads.{f}_head{h}_eq', text)

    def test_every_declaration_has_a_docstring(self):
        for rel, text in self.files.items():
            lines = text.splitlines()
            for i, line in enumerate(lines):
                if re.match(r'^(theorem|def) ', line):
                    self.assertTrue(lines[i - 1].rstrip().endswith('-/'), f'{rel}: {line}')

    def test_no_forbidden_constructs(self):
        for rel, text in self.files.items():
            self.assertIsNone(kg.FORBIDDEN.search(text), rel)

    def test_guard_rejects_forbidden_constructs(self):
        for bad in ('sorry', 'native_decide', 'decide +native', 'axiom foo : False', 'opaque x : Nat',
                    '@[implemented_by f]', '@[extern "c"]', 'unsafe def', 'admit', 'skipKernelTC'):
            with self.assertRaises(ValueError, msg=bad):
                kg.guard('theorem t : True := by\n  ' + bad + '\n' if bad != 'axiom foo : False' else bad + '\n')


class Determinism(unittest.TestCase):
    def test_regenerate_twice_byte_identical(self):
        d = small_data(5)
        a, _ = kg.emit(d)
        b, _ = kg.emit(d)
        self.assertEqual(a, b)

    def test_check_mode_detects_drift(self):
        files, _ = kg.emit(small_data())
        with tempfile.TemporaryDirectory() as tmp:
            out = Path(tmp)
            for rel, text in files.items():
                (out / rel).parent.mkdir(parents=True, exist_ok=True)
                (out / rel).write_text(text)
            self.assertEqual(kg.check_committed(files, out), [])
            p = out / 'TransformerBridge/Kronecker/Heads/CheckTU2.lean'
            p.write_text(p.read_text().replace('decide +kernel', 'decide +kernel '))
            (out / 'TransformerBridge/Kronecker/Heads/Extra.lean').write_text('')
            problems = kg.check_committed(files, out)
            self.assertIn('differs: TransformerBridge/Kronecker/Heads/CheckTU2.lean', problems)
            self.assertIn('unexpected: TransformerBridge/Kronecker/Heads/Extra.lean', problems)
            (out / 'TransformerBridge/Kronecker/Fields.lean').unlink()
            self.assertIn('missing: TransformerBridge/Kronecker/Fields.lean', kg.check_committed(files, out))


