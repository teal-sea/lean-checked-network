#!/usr/bin/env python3
"""Generate the whole-head Kronecker certificates for the TI and TU tables.

Emits 17 Lean modules under TransformerBridge/Kronecker/ (paths relative to this directory):

  Heads/CheckTI{h}.lean, Heads/CheckTU{h}.lean   one `decide +kernel` evaluation of `headCheck`
                                                 for head h (h = 0..3) and field TI or TU
  Heads/TI{h}.lean, Heads/TU{h}.lean             the head's table equality, by `TI_head_of_check`
                                                 or `TU_head_of_check` from `Kronecker.Spec`
  Fields.lean                                    the full-field equalities `TI_eq` and `TU_eq`

Inputs (repository-relative, each pinned by a committed sha256):

  transformer/runs/best.npz                        trained float64 weights
  transformer/mathlib/RawPacked-coefficients.json  canonical hashes of the quantised integer weights
  transformer/mathlib/RawPilot-pins.json           sha256 of best.npz and of the frozen-table files
  transformer/lean/Transformer/Net/W/*.lean        the frozen integer tables

The weights are quantised exactly as `int_transformer.quantise(W, 8)` does (each entry is
`floor(256 * w + 0.5)`), and the six fields used here must reproduce the committed canonical
hashes before anything is emitted. The emitted certificates refer to the accepted Lean data
modules (`TransformerBridge.RawPacked.Generated.*`, `TransformerCore.Net.*`) by name; the integers
read here only choose the bounds and the negative controls.

Bounds: `Kt, Kp, Kv, Ko, Kw` are the largest absolute entries of the data a head reads, `K` is the
crude output bound `128·Kw·32·Ko·128·(Kt+Kp)·Kv`, and `B = 2^k` is the smallest power of two with
`2K < B` and `2 ≤ B` (`base_exponent`). The kernel re-checks all of them inside `headCheck`, so a wrong choice can only make a
certificate fail; it cannot make a false statement pass.

Usage (standard library only):

  python3 kronecker_generate.py                  write the 17 modules
  python3 kronecker_generate.py --check          regenerate in memory and compare with the files
  python3 kronecker_generate.py --negatives DIR  also write the 8 negative controls and their
                                                 8 positive twins into DIR
  python3 kronecker_generate.py --crosscheck     recompute every frozen TI/TU row from the weights
                                                 (slow; supporting evidence, not part of the proof)
"""
import argparse
import ast
import hashlib
import json
import math
import re
import struct
import sys
import zipfile
from array import array
from pathlib import Path

HERE = Path(__file__).absolute().parent
ROOT = HERE.parent.parent

NS = 'TransformerBridge.Kronecker'
HEADS_NS = NS + '.Heads'
NEG_NS = NS + '.Negative'
DATA = 'TransformerBridge.RawPackedPilot.Data'
WEIGHTS = 'TransformerBridge.RawPackedPilot.weights'
GEN = 'TransformerBridge.RawPacked.Generated'
NETW = 'TransformerCore.Net.Weights'
TAB = 'TransformerCore.Net.tab'
TOOL = 'transformer/mathlib/kronecker_generate.py'

HEADS = range(4)
FIELDS = {'TI': ('Win', 512), 'TU': ('U', 113)}
NTOK, NPOS, DMODEL, DHEAD = 114, 3, 128, 32
SCALE = 256
SHAPES = {'tok': (114, 128), 'pos': (3, 128), 'WV': (4, 128, 32), 'WO': (4, 32, 128),
          'Win': (128, 512), 'U': (128, 113)}
# Serialized row layout of the accepted Lean data lists (axes of the original tensor).
AXES = {'tok': (0, 1), 'pos': (0, 1), 'WV': (0, 2, 1), 'WO': (0, 2, 1), 'Win': (1, 0), 'U': (1, 0)}
# Negative controls: Win row 7 at the first coordinate whose head-h TI sensitivity is non-zero,
# and frozen TI1 entry (token 5, component 7).
WIN_CONTROL_ROW = 7
TABLE_CONTROL = (1, 5, 7)

FORBIDDEN = re.compile(r'sorry|\b(admit|unsafe)\b|native_decide|^\s*axiom |opaque |implemented_by|'
                       r'extern|skipKernelTC|decide \+native', re.M)

HEADER = ('-- Generated by {tool}. Do not edit by hand.\n'
          '-- Inputs: transformer/runs/best.npz (quantised at S = 256), the committed canonical\n'
          '-- coefficient hashes, and the frozen tables transformer/lean/Transformer/Net/W/*.lean.\n'
          '-- Regenerate with `python3 {tool}`; `--check` compares this file with a fresh run.\n')


class InputError(ValueError):
    """A pinned input is missing, changed, or malformed."""


# ---------------------------------------------------------------------------------------------
# Inputs


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def verify_pins(root):
    """Check best.npz and the frozen-table sources against RawPilot-pins.json and W.sha256."""
    pins = json.loads((root / 'transformer/mathlib/RawPilot-pins.json').read_text())
    needed = ['transformer/runs/best.npz', 'transformer/lean/Transformer/Net/W.sha256',
              'transformer/lean/Transformer/Net/Weights.lean']
    needed += [k for k in pins if k.startswith('transformer/lean/Transformer/Net/W/')]
    for rel in needed:
        if rel not in pins:
            raise InputError('no pin for ' + rel)
        if sha256(root / rel) != pins[rel]:
            raise InputError('pinned input changed: ' + rel)
    net = root / 'transformer/lean/Transformer/Net'
    listed = {}
    for line in (net / 'W.sha256').read_text().splitlines():
        digest, name = line.split()
        listed[name] = digest
    on_disk = {'W/' + p.name for p in (net / 'W').glob('*.lean')}
    if set(listed) != on_disk:
        raise InputError('Net/W.sha256 does not list exactly the files in Net/W/')
    for name, digest in listed.items():
        if sha256(net / name) != digest:
            raise InputError('frozen table file changed: ' + name)
    return {rel: pins[rel] for rel in sorted(needed)}


def read_npy(data):
    """Parse a little-endian float64, C-ordered .npy (format 1.x or 2.x) into (shape, values)."""
    if data[:6] != b'\x93NUMPY':
        raise InputError('not an .npy file')
    major = data[6]
    if major == 1:
        (hlen,), start = struct.unpack('<H', data[8:10]), 10
    elif major in (2, 3):
        (hlen,), start = struct.unpack('<I', data[8:12]), 12
    else:
        raise InputError('unsupported .npy version')
    header = ast.literal_eval(data[start:start + hlen].decode('latin1'))
    if header.get('descr') != '<f8' or header.get('fortran_order') is not False:
        raise InputError('expected little-endian float64 in C order')
    shape = tuple(header['shape'])
    values = array('d')
    values.frombytes(data[start + hlen:])
    if sys.byteorder != 'little':
        values.byteswap()
    if len(values) != math.prod(shape):
        raise InputError('wrong .npy payload size')
    return shape, values


def quantise(values, key):
    """`int_transformer.quantise` for the fields used here: round half up of 256·w."""
    if key in ('bin', 'bout', 'WQ'):
        raise InputError('field not used by the TI/TU certificates: ' + key)
    out = []
    for w in values:
        if not math.isfinite(w):
            raise InputError('non-finite weight in ' + key)
        out.append(int(math.floor(SCALE * w + 0.5)))
    return out


def canonical_hash(flat):
    return hashlib.sha256(json.dumps(flat, separators=(',', ':')).encode()).hexdigest()


def serialize(flat, shape, axes):
    """Rows of the accepted Lean data list: the tensor transposed by `axes`, then flattened to
    rows of the last arranged dimension."""
    strides = [math.prod(shape[i + 1:]) for i in range(len(shape))]
    arranged = [shape[a] for a in axes]
    width = arranged[-1]
    rows = []
    for outer in range(math.prod(arranged[:-1])):
        idx, rem = [], outer
        for n in reversed(arranged[:-1]):
            idx.append(rem % n)
            rem //= n
        idx.reverse()
        base = sum(strides[a] * i for a, i in zip(axes[:-1], idx))
        rows.append([flat[base + strides[axes[-1]] * c] for c in range(width)])
    return rows


def load_weights(root):
    """The six integer weight fields, in the serialized row layout of the Lean data lists."""
    expected = json.loads((root / 'transformer/mathlib/RawPacked-coefficients.json').read_text())
    expected = expected['coefficients']
    data = {}
    with zipfile.ZipFile(root / 'transformer/runs/best.npz') as z:
        for key, shape in SHAPES.items():
            got_shape, values = read_npy(z.read(key + '.npy'))
            if got_shape != shape:
                raise InputError(f'{key}: shape {got_shape}, expected {shape}')
            flat = quantise(values, key)
            if canonical_hash(flat) != expected[key]['canonical_flat_integer_json_sha256']:
                raise InputError(f'{key}: quantised weights differ from the committed canonical hash')
            if list(expected[key]['serialized_axes']) != list(AXES[key]):
                raise InputError(f'{key}: serialized layout differs from the committed one')
            data[key] = serialize(flat, shape, AXES[key])
    return data


LIT = re.compile(r'\(\.ofNat (\d+)\)|\(\.negSucc (\d+)\)')


def parse_ints(body):
    out = [int(a) if a else -int(b) - 1 for a, b in LIT.findall(body)]
    if (body.count(',') + 1 if body.strip() else 0) != len(out):
        raise InputError('non-literal list element in frozen table')
    return out


def load_tables(root):
    """Frozen rows `Net.{TI,TU}{0,1}[h][tk]` and `Net.{TI,TU}2[h]` from the committed sources."""
    net = root / 'transformer/lean/Transformer/Net'
    weights = (net / 'Weights.lean').read_text()
    for key in ('TI0', 'TI1', 'TU0', 'TU1'):
        if not re.search(rf'^def {key} : List \(List \(List Int\)\) := \[{key}_0, {key}_1, {key}_2, {key}_3\]',
                         weights, re.M):
            raise InputError('unexpected layout of Net.' + key)
    if 'TI0 := TI0, TI1 := TI1, TI2 := TI2' not in weights or 'TU0 := TU0, TU1 := TU1, TU2 := TU2' not in weights:
        raise InputError('unexpected layout of Net.tab')
    vectors, lists = {}, {}
    for path in sorted((net / 'W').glob('*.lean')):
        text = path.read_text()
        for name, body in re.findall(r'^def (\S+) : List Int := \[(.*)\]\s*$', text, re.M):
            vectors[name] = parse_ints(body)
        for name, body in re.findall(r'^def (\S+) : List \(List Int\) := \[(.*)\]\s*$', text, re.M):
            lists[name] = [x.strip() for x in body.split(',')]
    tables = {}
    for key in ('TI0', 'TI1', 'TU0', 'TU1'):
        tables[key] = [[vectors[n] for n in lists[f'{key}_{h}']] for h in HEADS]
    for key in ('TI2', 'TU2'):
        tables[key] = [vectors[n] for n in lists[key]]
    return tables


# ---------------------------------------------------------------------------------------------
# Bounds and controls


def params(data, h, field):
    """Bounds for head h and field TI or TU, chosen from the data (re-checked by the kernel)."""
    mat = FIELDS[field][0]
    bound = {
        'Kt': max(abs(x) for row in data['tok'] for x in row),
        'Kp': max(abs(x) for row in data['pos'] for x in row),
        'Kv': max(abs(x) for row in data['WV'][h * DHEAD:(h + 1) * DHEAD] for x in row),
        'Ko': max(abs(x) for row in data['WO'][h * DMODEL:(h + 1) * DMODEL] for x in row),
        'Kw': max(abs(x) for row in data[mat] for x in row),
    }
    K = 128 * bound['Kw'] * (32 * bound['Ko'] * (128 * (bound['Kt'] + bound['Kp']) * bound['Kv']))
    k = base_exponent(K)
    return dict(bound, K=K, k=k, B=2 ** k)


def base_exponent(K):
    """Smallest `k` with `2K < 2^k` and `2 ≤ 2^k`, the two base conditions `headCheck` re-checks."""
    return max(1, (2 * K).bit_length())


def ovec(data, h, tk, j):
    """`Weights.ovec h tk j` of Transformer/Raw.lean, from the serialized rows."""
    x = [data['tok'][tk][e] + data['pos'][j][e] for e in range(DMODEL)]
    WV = data['WV'][h * DHEAD:(h + 1) * DHEAD]       # WV[l][e]
    WO = data['WO'][h * DMODEL:(h + 1) * DMODEL]     # WO[d][l]
    v = [sum(x[e] * WV[l][e] for e in range(DMODEL)) for l in range(DHEAD)]
    return [sum(v[l] * WO[d][l] for l in range(DHEAD)) for d in range(DMODEL)]


def win_control(data, h, P):
    """Win row `WIN_CONTROL_ROW`, first coordinate e with ovec(h, 0, 0)[e] ≠ 0 whose +1 stays
    within Kw: the head-h TI entry (j = 0, tk = 0, i = row) then changes by ovec[e] ≠ 0."""
    o = ovec(data, h, 0, 0)
    i = WIN_CONTROL_ROW
    for e in range(DMODEL):
        x = data['Win'][i][e]
        if o[e] != 0 and abs(x + 1) <= P['Kw']:
            return {'row_i': i, 'coord_e': e, 'old': x, 'new': x + 1, 'sensitivity': o[e]}
    raise InputError('no admissible Win control coordinate')


def reference_rows(data, h):
    """Every frozen TI/TU row of head h recomputed from the weights (supporting evidence only)."""
    WinT = list(zip(*data['Win']))
    UT = list(zip(*data['U']))

    def site(tk, j):
        o = ovec(data, h, tk, j)
        return ([sum(o[d] * WinT[d][i] for d in range(DMODEL)) for i in range(512)],
                [sum(o[d] * UT[d][k] for d in range(DMODEL)) for k in range(113)])
    out = {'TI0': [], 'TI1': [], 'TU0': [], 'TU1': []}
    for j in (0, 1):
        for tk in range(NTOK):
            ti, tu = site(tk, j)
            out[f'TI{j}'].append(ti)
            out[f'TU{j}'].append(tu)
    out['TI2'], out['TU2'] = site(113, 2)
    return out


# ---------------------------------------------------------------------------------------------
# Emission


def lit(n):
    return f'(.ofNat {n})' if n >= 0 else f'(.negSucc {-n - 1})'


def vec(xs):
    return '[' + ', '.join(lit(x) for x in xs) + ']'


def guard(text):
    hit = FORBIDDEN.search(text)
    if hit:
        raise ValueError('forbidden construct in emitted Lean: ' + hit.group(0))
    return text


# Controls only: when the kernel rejects, `decide +kernel` re-evaluates the check at Meta level to
# print "proved that the proposition ... is false"; with the default recursion depth that
# re-evaluation fails and only a raw kernel type mismatch is reported. The certificates themselves
# need no option.
CONTROL_OPTIONS = ('-- Needed only for the diagnostic: Meta-level re-evaluation of a failing check.\n'
                   'set_option maxRecDepth 100000\n')


def module(imports, doc, namespace, body, opens=(), options=''):
    text = HEADER.format(tool=TOOL)
    text += ''.join(f'import {m}\n' for m in imports)
    text += f'\n/-!\n{doc}\n-/\n\nset_option autoImplicit false\n{options}\nnamespace {namespace}\n\n'
    text += ''.join(f'open {o}\n' for o in opens) + ('\n' if opens else '')
    text += body + f'\nend {namespace}\n'
    return guard(text)


def check_imports(field):
    return [NS + '.Core'] + [f'{GEN}.{k}' for k in ('tok', 'pos', 'WV', 'WO', FIELDS[field][0])] + [NETW]


def check_term(P, field, h, mout=None, tab=TAB):
    mat, n = FIELDS[field]
    mout = mout or f'Data.{mat}'
    return (f'headCheck {P["B"]} {P["K"]} {P["Kt"]} {P["Kp"]} {P["Kv"]} {P["Ko"]} {P["Kw"]} {n} {h}\n'
            f'      Data.tok Data.pos Data.WV Data.WO {mout}\n'
            f'      (nth [] {tab}.{field}0 {h}) (nth [] {tab}.{field}1 {h})\n'
            f'      (nth [] {tab}.{field}2 {h})')


def check_source(P, field, h):
    mat, n = FIELDS[field]
    doc = (f'# Head {h}, field `{field}`: the whole-head check\n\n'
           f'One kernel evaluation of `headCheck` over the raw data lists `Data.tok`, `Data.pos`,\n'
           f'`Data.WV`, `Data.WO`, `Data.{mat}` and the frozen rows `{field}0`, `{field}1`, `{field}2` of\n'
           f'head {h}. The bounds were chosen by the generator from the data and are re-checked by the\n'
           f'kernel: `Kt = {P["Kt"]}`, `Kp = {P["Kp"]}`, `Kv = {P["Kv"]}`, `Ko = {P["Ko"]}`, '
           f'`Kw = {P["Kw"]}`,\n'
           f'`K = {P["K"]}` and `B = 2^{P["k"]}`.')
    body = (f'/-- `headCheck` passes for head {h}, field `{field}` ({mat}, {n} columns). -/\n'
            f'theorem check{field}{h} :\n    {check_term(P, field, h)} = true := by\n  decide +kernel\n')
    return module(check_imports(field), doc, HEADS_NS, body,
                  opens=(f'{NS} (headCheck)', 'TransformerCore (nth)', 'TransformerBridge.RawPackedPilot'))


def head_source(field, h):
    mat = FIELDS[field][0]
    doc = (f'# Head {h}, field `{field}`: the table equality\n\n'
           f'`{field}_head_of_check` turns the passing check `check{field}{h}` into the equality of the\n'
           f'frozen `{field}` table of head {h} with the raw model\'s, for every scale, position and token.\n'
           f'The five data bridges are `rfl`: `RawPackedPilot.weights` reads the same lists.')
    body = (f'/-- Head {h}, field `{field}`: every slot of the frozen table equals the raw model\'s, at every\n'
            f'scale `S`. -/\n'
            f'theorem {field}_head{h} (S : Nat) (j : Fin 3) (tk : Fin 114) :\n'
            f'    (toTables {TAB}).{field} {h} j tk = (weights.rawTables S).{field} {h} j tk :=\n'
            f'  {field}_head_of_check weights S {TAB} {h} Data.tok Data.pos Data.WV Data.WO Data.{mat}\n'
            f'    (fun _ _ => rfl) (fun _ _ => rfl) (fun _ _ => rfl) (fun _ _ => rfl) (fun _ _ => rfl)\n'
            f'    check{field}{h} j tk\n\n'
            f'/-- Head {h}, field `{field}`, as one function equality at `S = 256`. -/\n'
            f'theorem {field}_head{h}_eq :\n'
            f'    (toTables {TAB}).{field} {h} = (weights.rawTables 256).{field} {h} := by\n'
            f'  funext j tk\n'
            f'  exact {field}_head{h} 256 j tk\n')
    imports = [NS + '.Spec', f'{GEN}.Weights', NETW, f'{HEADS_NS}.Check{field}{h}']
    return module(imports, doc, HEADS_NS, body,
                  opens=(NS, 'TransformerBridge (toTables)', 'TransformerBridge.RawPackedPilot'))


def fields_source():
    doc = ('# The `TI` and `TU` tables equal the raw model\'s\n\n'
           'The per-head equalities of `Kronecker.Heads`, combined over the four heads. These are the\n'
           '`TI` and `TU` hypotheses of the full table identity in `TransformerBridge.FinalRaw`.')
    body = ''
    for field in FIELDS:
        cases = ''.join(f'  · exact Heads.{field}_head{h}_eq\n' for h in HEADS)
        body += (f'/-- The frozen `{field}` tables are exactly the raw model\'s at `S = 256`, all four heads. -/\n'
                 f'theorem {field}_eq :\n'
                 f'    (toTables {TAB}).{field} = ({WEIGHTS}.rawTables 256).{field} := by\n'
                 f'  funext h\n  fin_cases h\n{cases}\n')
    imports = [f'{HEADS_NS}.{f}{h}' for f in FIELDS for h in HEADS]
    return module(imports, doc, NS, body.rstrip('\n') + '\n', opens=('TransformerBridge (toTables)',))


def negative_win_source(data, P, h, ctl, delta=1):
    """The changed-`Win` control (`delta = 1`, must fail) or its positive twin (`delta = 0`, the
    same file with the row unchanged, must pass)."""
    i = ctl['row_i']
    row = list(data['Win'][i])
    row[ctl['coord_e']] += delta
    names = ', '.join(f'Data.Win_{t}' if t != i else f'Win_{i}_changed' for t in range(512))
    kind = 'Negative control' if delta else 'Positive twin'
    ns = f'{NEG_NS}.Win{h}' + ('' if delta else 'Twin')
    change = (f'{ctl["old"]} → {ctl["old"] + delta}' if delta else f'{ctl["old"]}, unchanged')
    verdict = ('This changes the head-{h}\n`TI` entry (j = 0, tk = 0, i = {i}) by {s}, so the check must be '
               'rejected by the\nkernel with a `decide` failure.' if delta else
               'The data equal the real\nweights, so the check must pass.').format(h=h, i=i, s=ctl['sensitivity'])
    doc = (f'# {kind}: head {h}, `TI`, raw weight `Win` row {i}\n\n'
           f'`Win` row {i}, coordinate {ctl["coord_e"]}: {change}. {verdict}')
    body = (f'/-- `Win` row {i} with coordinate {ctl["coord_e"]} increased by {delta}. -/\n'
            f'def Win_{i}_changed : List Int := {vec(row)}\n\n'
            f'/-- `Data.Win` with row {i} replaced. -/\n'
            f'def WinChanged : List (List Int) := [{names}]\n\n'
            f'/-- {"Must fail" if delta else "Must pass"}: the frozen `TI` rows of head {h} against this `Win`. -/\n'
            f'theorem check_changed :\n    {check_term(P, "TI", h, mout="WinChanged")} = true := by\n  decide +kernel\n')
    return module(check_imports('TI'), doc, ns, body,
                  opens=(f'{NS} (headCheck)', 'TransformerCore (nth)', 'TransformerBridge.RawPackedPilot'),
                  options=CONTROL_OPTIONS)


def negative_table_source(tables, P, h, delta=1):
    """The changed-table control (`delta = 1`, must fail) or its positive twin (`delta = 0`)."""
    j, tk, i = TABLE_CONTROL
    rows = tables[f'TI{j}'][h]
    row = list(rows[tk])
    row[i] += delta
    names = ', '.join(f'TransformerCore.Net.TI{j}_{h}_{t}' if t != tk else f'TI{j}_{h}_{tk}_changed'
                      for t in range(NTOK))
    heads = ', '.join(f'TransformerCore.Net.TI{j}_{g}' if g != h else f'TI{j}_{h}_changed' for g in HEADS)
    kind = 'Negative control' if delta else 'Positive twin'
    ns = f'{NEG_NS}.Table{h}' + ('' if delta else 'Twin')
    change = f'{rows[tk][i]} → {rows[tk][i] + delta}' if delta else f'{rows[tk][i]}, unchanged'
    verdict = ('The check\nmust be rejected by the kernel with a `decide` failure.' if delta else
               'The table equals the\nfrozen one, so the check must pass.')
    doc = (f'# {kind}: head {h}, `TI`, frozen table entry\n\n'
           f'Frozen `TI{j}` of head {h}, token {tk}, component {i}: {change}. {verdict}')
    body = (f'/-- Frozen row `TI{j}[{h}][{tk}]` with component {i} increased by {delta}. -/\n'
            f'def TI{j}_{h}_{tk}_changed : List Int := {vec(row)}\n\n'
            f'/-- Frozen `TI{j}[{h}]` with row {tk} replaced. -/\n'
            f'def TI{j}_{h}_changed : List (List Int) := [{names}]\n\n'
            f'/-- The frozen tables with that one row replaced. -/\n'
            f'def tabChanged : TransformerCore.Tab := {{ {TAB} with TI{j} := [{heads}] }}\n\n'
            f'/-- {"Must fail" if delta else "Must pass"}: these frozen rows against the raw weights. -/\n'
            f'theorem check_changed :\n    {check_term(P, "TI", h, tab="tabChanged")} = true := by\n  decide +kernel\n')
    meta = {'j': j, 'tk': tk, 'i': i, 'old': rows[tk][i], 'new': rows[tk][i] + delta}
    return module(check_imports('TI'), doc, ns, body,
                  opens=(f'{NS} (headCheck)', 'TransformerCore (nth)', 'TransformerBridge.RawPackedPilot'),
                  options=CONTROL_OPTIONS), meta


def emit(data):
    """All 17 modules as {relative path: text}, plus the parameter table."""
    out, table = {}, {}
    for h in HEADS:
        for field in FIELDS:
            P = params(data, h, field)
            table[f'{field}{h}'] = P
            out[f'TransformerBridge/Kronecker/Heads/Check{field}{h}.lean'] = check_source(P, field, h)
            out[f'TransformerBridge/Kronecker/Heads/{field}{h}.lean'] = head_source(field, h)
    out['TransformerBridge/Kronecker/Fields.lean'] = fields_source()
    return dict(sorted(out.items())), table


def emit_negatives(data, tables):
    """The 8 negative controls and their 8 positive twins, as {file name: text}."""
    out, meta = {}, {}
    for h in HEADS:
        P = params(data, h, 'TI')
        ctl = win_control(data, h, P)
        out[f'negative-win-h{h}.lean'] = negative_win_source(data, P, h, ctl)
        out[f'positive-win-h{h}.lean'] = negative_win_source(data, P, h, ctl, delta=0)
        text, tmeta = negative_table_source(tables, P, h)
        out[f'negative-table-h{h}.lean'] = text
        out[f'positive-table-h{h}.lean'] = negative_table_source(tables, P, h, delta=0)[0]
        meta[f'win-h{h}'] = ctl
        meta[f'table-h{h}'] = tmeta
    return dict(sorted(out.items())), meta


def check_committed(files, outdir):
    """Compare the regenerated modules with the files on disk; return a list of problems."""
    problems = []
    for rel, text in files.items():
        p = outdir / rel
        if not p.exists():
            problems.append('missing: ' + rel)
        elif p.read_text() != text:
            problems.append('differs: ' + rel)
    heads = outdir / 'TransformerBridge/Kronecker/Heads'
    if heads.is_dir():
        extra = {str(p.relative_to(outdir)) for p in heads.glob('*.lean')} - set(files)
        problems += ['unexpected: ' + rel for rel in sorted(extra)]
    return problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='compare with the committed files; write nothing')
    mode.add_argument('--negatives', type=Path, help='also write the 8 negative controls and 8 positive twins here')
    ap.add_argument('--crosscheck', action='store_true', help='recompute every frozen TI/TU row (slow)')
    ap.add_argument('--root', type=Path, default=ROOT, help='repository root (default: inferred)')
    ap.add_argument('--out', type=Path, default=HERE, help='output directory (default: transformer/mathlib)')
    args = ap.parse_args(argv)
    pins = verify_pins(args.root)
    data = load_weights(args.root)
    tables = load_tables(args.root)
    files, table = emit(data)
    report = {'pins': pins, 'modules': list(files),
              'parameters': {k: {n: str(v) for n, v in P.items()} for k, P in table.items()}}
    if args.crosscheck:
        mismatches = {}
        for h in HEADS:
            ref = reference_rows(data, h)
            for key, rows in ref.items():
                frozen = tables[key][h]
                mismatches[f'{key}[{h}]'] = sum(a != b for a, b in zip(rows, frozen)) + abs(len(rows) - len(frozen))
        report['crosscheck_mismatches'] = mismatches
        if any(mismatches.values()):
            print(json.dumps(report, indent=1))
            return 1
    if args.check:
        problems = check_committed(files, args.out)
        report['check'] = problems or 'identical'
        print(json.dumps(report, indent=1))
        return 1 if problems else 0
    for rel, text in files.items():
        p = args.out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
    if args.negatives:
        neg, meta = emit_negatives(data, tables)
        args.negatives.mkdir(parents=True, exist_ok=True)
        for name, text in neg.items():
            (args.negatives / name).write_text(text)
        report['negatives'] = meta
    print(json.dumps(report, indent=1))
    return 0


if __name__ == '__main__':
    sys.exit(main())
