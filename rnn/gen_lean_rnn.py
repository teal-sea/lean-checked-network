"""Write a frozen recurrent adder into the Lean package as literals, with its reachable states.

Usage: python3 gen_lean_rnn.py FROZEN.npz NAME [FLIP]
  NAME  Lean namespace, e.g. Trained
  FLIP  optional "matrix,i,j,newvalue" to plant a fault (expected_fail file)
"""
import sys
from pathlib import Path
import numpy as np
sys.path.insert(0, str(Path(__file__).resolve().parent))
from freeze_check import check

src, name = sys.argv[1], sys.argv[2]
Q = {k: v for k, v in np.load(src).items()}
flip = None
if len(sys.argv) > 3:
    mat, i, j, val = sys.argv[3].split(",")
    i, j, val = int(i), int(j), int(val)
    old = Q[mat][i, j] if Q[mat].ndim == 2 else Q[mat][i]
    if Q[mat].ndim == 2: Q[mat][i, j] = val
    else: Q[mat][i] = val
    flip = f"{mat}[{i}][{j}] changed from {old} to {val}"
ok, nreach, margin = check(Q, verbose=False)
# the reachable states, in breadth-first order, recomputed here so the list matches these weights
H = Q["Wh"].shape[0]
def step(h, x):
    pre = Q["Wh"] @ np.array(h) + Q["Wx"] @ np.array(x) + Q["bh"]
    return tuple(int(v) for v in (pre > 0))
h0 = tuple([0] * H); reach = [h0]; seen = {h0}; q = [h0]
while q:
    h = q.pop(0)
    for x in [(0, 0), (0, 1), (1, 0), (1, 1)]:
        h2 = step(h, x)
        if h2 not in seen: seen.add(h2); reach.append(h2); q.append(h2)

def lit(x):
    x = int(x)
    return f"(.ofNat {x})" if x >= 0 else f"(.negSucc {-x - 1})"
def ilist(v): return "[" + ", ".join(lit(x) for x in v) + "]"
def state(h): return "[" + ", ".join("true" if b else "false" for b in h) + "]"

out_dir = Path(__file__).resolve().parent / "lean" / ("expected_fail" if flip else "RnnAdder")
out_dir.mkdir(parents=True, exist_ok=True)
head = (f"Planted fault: {flip}. This file must be REJECTED by the kernel." if flip else
        f"The trained recurrent adder, weights frozen to whole numbers in [-127, 127], and the {nreach} states "
        f"it reaches from the all-zero state. Generated by `gen_lean_rnn.py` from `{Path(src).name}`.")
text = f"""import RnnAdder.Network

/-!
# {head}

`.ofNat n` is the integer n and `.negSucc n` is the integer -(n + 1). `H = {H}` units.
Certificate check in Python: {'holds' if ok else 'FAILS'}; smallest |pre-activation| on a reachable transition: {margin}.
-/

namespace RnnAdder.{name}

open RnnAdder

def net : Net := {{
  Wh := [
{chr(10).join('    ' + ilist(r) + ',' for r in Q['Wh'])[:-1]}],
  Wxa := {ilist(Q['Wx'][:, 0])},
  Wxb := {ilist(Q['Wx'][:, 1])},
  bh := {ilist(Q['bh'])},
  Wo := {ilist(Q['Wo'])},
  Woa := {lit(Q['Wox'][0])},
  Wob := {lit(Q['Wox'][1])},
  bo := {lit(Q['bo'])},
  Wc := {ilist(Q['Wc'])},
  bc := {lit(Q['bc'])},
  h0 := {state(h0)},
  reach := [
{chr(10).join('    ' + state(h) + ',' for h in reach)[:-1]}]
}}

/-- The finite check: the kernel evaluates `transOk` on the {nreach} reachable states and 4 inputs. -/
theorem trans_ok : transOk net = true := by decide +kernel
"""
if not flip:
    text += f"""
/-- The network's sum bits equal the ripple-carry adder's, for every input list. -/
theorem sums_correct (xs : List Input) : run net net.h0 xs = addBits false xs :=
  run_eq_addBits net trans_ok xs

/-- The network's final carry equals the ripple-carry adder's, for every input list. -/
theorem carry_correct (xs : List Input) : finalCarry net net.h0 xs = carryOut false xs :=
  finalCarry_eq_carryOut net trans_ok xs

/-- The network adds two numbers of any length: the number spelled by its sum bits, plus its
final carry at position `n`, equals the sum of the two inputs. -/
theorem adds (xs : List Input) :
    bitsToNat (run net net.h0 xs) + 2 ^ xs.length * (if finalCarry net net.h0 xs then 1 else 0)
      = bitsToNat (xs.map Prod.fst) + bitsToNat (xs.map Prod.snd) :=
  network_adds net trans_ok xs
"""
text += f"\nend RnnAdder.{name}\n"
fn = out_dir / f"{name}.lean"
fn.write_text(text)
print(f"wrote {fn}: H={H}, {nreach} reachable states, python certificate {'holds' if ok else 'FAILS'}, margin {margin}" + (f", fault: {flip}" if flip else ""))
