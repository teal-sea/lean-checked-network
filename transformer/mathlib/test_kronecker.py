class Negatives(unittest.TestCase):
    def setUp(self):
        self.d = small_data(11)
        self.tables = {k: [[[0] * (512 if k.startswith('TI') else 113)] * 114 for _ in range(4)]
                       for k in ('TI0', 'TI1', 'TU0', 'TU1')}
        self.tables['TI2'] = [[0] * 512 for _ in range(4)]
        self.tables['TU2'] = [[0] * 113 for _ in range(4)]
        self.neg, self.meta = kg.emit_negatives(self.d, self.tables)

    def test_eight_controls_and_eight_twins(self):
        names = [f'{s}-{k}-h{h}.lean' for s in ('negative', 'positive') for k in ('table', 'win') for h in range(4)]
        self.assertEqual(sorted(self.neg), sorted(names))
        for name, text in self.neg.items():
            self.assertEqual(text.count('decide +kernel'), 1, name)
            self.assertIsNone(kg.FORBIDDEN.search(text), name)
            self.assertTrue(declarations(text)[-1].endswith('.check_changed'))
            # The diagnostic of a failing decide needs the larger recursion depth; nothing else.
            self.assertIn('set_option maxRecDepth 100000\n', text)
            self.assertNotIn('maxHeartbeats', text)

    def test_twin_differs_from_its_control_only_in_the_changed_value(self):
        for h in range(4):
            for k in ('win', 'table'):
                def code(t):
                    # imports and options, then everything after the module docstring; the
                    # namespace (Win0 vs Win0Twin) and docstrings are the only allowed prose changes
                    lines = t.splitlines()
                    head = [l for l in lines if l.startswith(('import ', 'set_option'))]
                    body = lines[lines.index(next(l for l in lines if l.startswith('namespace '))) + 1:]
                    return head + [l for l in body if not l.startswith(('/--', 'end '))]
                neg = code(self.neg[f'negative-{k}-h{h}.lean'])
                pos = code(self.neg[f'positive-{k}-h{h}.lean'])
                self.assertEqual(len(neg), len(pos))
                diff = [i for i, (a, b) in enumerate(zip(neg, pos)) if a != b]
                changed = [i for i in diff if 'List Int :=' in neg[i] and '_changed :' in neg[i]]
                self.assertEqual(len(changed), 1, (h, k))
                a = kg.parse_ints(neg[changed[0]].split(':= [', 1)[1].rstrip(']'))
                b = kg.parse_ints(pos[changed[0]].split(':= [', 1)[1].rstrip(']'))
                self.assertEqual(sum(x - y for x, y in zip(a, b)), 1)
                self.assertEqual(sum(x != y for x, y in zip(a, b)), 1)
                self.assertEqual(diff, changed, (h, k))

    def test_positive_modules_carry_no_resource_options(self):
        files, _ = kg.emit(self.d)
        for rel, text in files.items():
            self.assertNotIn('maxRecDepth', text, rel)

    def test_win_control_changes_one_coordinate_with_nonzero_sensitivity(self):
        for h in range(4):
            ctl = self.meta[f'win-h{h}']
            self.assertEqual(ctl['new'], ctl['old'] + 1)
            self.assertEqual(ctl['old'], self.d['Win'][ctl['row_i']][ctl['coord_e']])
            self.assertNotEqual(ctl['sensitivity'], 0)
            self.assertEqual(ctl['sensitivity'], kg.ovec(self.d, h, 0, 0)[ctl['coord_e']])
            text = self.neg[f'negative-win-h{h}.lean']
            changed = re.search(r'^def Win_7_changed : List Int := \[(.*)\]$', text, re.M).group(1)
            row = kg.parse_ints(changed)
            diff = [e for e in range(128) if row[e] != self.d['Win'][7][e]]
            self.assertEqual(diff, [ctl['coord_e']])
            self.assertIn('Data.Win_6, Win_7_changed, Data.Win_8', text)

    def test_table_control_changes_one_entry(self):
        for h in range(4):
            m = self.meta[f'table-h{h}']
            self.assertEqual((m['j'], m['tk'], m['i'], m['new'] - m['old']), (1, 5, 7, 1))
            text = self.neg[f'negative-table-h{h}.lean']
            self.assertIn(f'def tabChanged : TransformerCore.Tab := {{ TransformerCore.Net.tab with TI1 :=', text)
            self.assertIn(f'TI1_{h}_changed', text)


class Inputs(unittest.TestCase):
    def test_npy_roundtrip(self):
        import struct
        vals = [0.5, -1.25, 3.0, 1e-3, -7.75, 2.5]
        header = "{'descr': '<f8', 'fortran_order': False, 'shape': (2, 3), }"
        header += ' ' * (63 - len(header)) + '\n'
        raw = b'\x93NUMPY\x01\x00' + struct.pack('<H', len(header)) + header.encode() + struct.pack('<6d', *vals)
        shape, got = kg.read_npy(raw)
        self.assertEqual(shape, (2, 3))
        self.assertEqual(list(got), vals)

    def test_quantise_rounds_half_up(self):
        self.assertEqual(kg.quantise([0.5 / 256, -0.5 / 256, 1.2 / 256, -1.7 / 256], 'tok'), [1, 0, 1, -2])

    def test_serialize_matches_axes(self):
        shape = (2, 3, 4)
        flat = list(range(24))
        rows = kg.serialize(flat, shape, (0, 2, 1))
        self.assertEqual(len(rows), 8)
        self.assertEqual(rows[0], [0, 4, 8])        # h = 0, l = 0: entries (0, d, 0)
        self.assertEqual(rows[5], [13, 17, 21])     # h = 1, l = 1
        self.assertEqual(kg.serialize(list(range(6)), (2, 3), (1, 0)), [[0, 3], [1, 4], [2, 5]])

    def test_parse_rejects_non_literals(self):
        self.assertEqual(kg.parse_ints('(.ofNat 3), (.negSucc 0)'), [3, -1])
        with self.assertRaises(kg.InputError):
            kg.parse_ints('(.ofNat 3), x')

    @unittest.skipUnless((kg.ROOT / 'transformer/runs/best.npz').exists()
                         or os.environ.get('KRONECKER_REQUIRE_INPUTS'), 'repository inputs not present')
    def test_committed_modules_are_current(self):
        pins = kg.verify_pins(kg.ROOT)
        self.assertIn('transformer/runs/best.npz', pins)
        files, table = kg.emit(kg.load_weights(kg.ROOT))
        self.assertEqual(kg.check_committed(files, HERE), [])
        self.assertEqual(table['TI0']['K'], 49761849704448)
        self.assertEqual(table['TU3']['k'], 46)


