"""Train one network, freeze it, build its circle-only reduction, and kernel-check both.

Usage: python3 run_one.py P H SEED FRAC WD STEPS OUTDIR [--repo DIR] [--chunks N] [--jobs N]

Stages, in order (each one is timed and recorded in OUTDIR/result.json):
  1. train     the repo's train.py (subprocess, OMP_NUM_THREADS=1) -> OUTDIR/trained.npz
  2. circle    the repo's circle_only.py -> OUTDIR/circle_only.npz; if its W2 falls outside
               [-128, 127] or the fast evaluator's digit bound would fail, all three tables are
               rescaled by one common factor before rounding -> OUTDIR/circle_only_scaled.npz
  3. numpy     wrong pairs, smallest winning gap and ties for both frozen networks
  4. gen       a fresh Lean package in OUTDIR/lean with one theorem per row for each network
  5. build     lake build
  6. replay    lake env leanchecker on every generated module
  7. axioms    #print axioms of both main theorems
  8. scan      the package contains no sorry / native_decide / axiom / opaque / implemented_by / extern

The theorem for each network states exactly where it is wrong: for every pair (a, b),
answer a b = (a + b) % p  if and only if  (a, b) is not in an explicit list. The list is also
checked to have length k, to be strictly increasing (so no pair is listed twice) and to hold only
pairs with both entries below p, so k is the number of wrong inputs. When the list is empty the
generated file also states adds_mod_p, the repo's theorem.

Exit code is non-zero if any stage fails. The kernel verdicts in result.json come only from
lake build, leanchecker and #print axioms; nothing is reported as checked unless those passed.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
STANDARD_AXIOMS = ["propext", "Classical.choice", "Quot.sound"]
FORBIDDEN = ["sorry", "native_decide", "implemented_by", "extern", "opaque", "axiom ", "skipKernelTC"]


def lit(x):
    """An Int literal written as a constructor, so the kernel does no typeclass unfolding."""
    x = int(x)
    return f"(.ofNat {x})" if x >= 0 else f"(.negSucc {-x - 1})"


def table(m):
    return "[\n" + ",\n".join("  [" + ", ".join(lit(x) for x in row) + "]" for row in m) + "]"


def evaluate(E1, E2, W2):
    """Every answer, exactly as Network.lean defines it (highest score, first index on a tie)."""
    p = E1.shape[0]
    a, b = np.divmod(np.arange(p * p), p)
    z = E1[a].astype(np.int64) + E2[b].astype(np.int64)
    hidden = z * z
    S = hidden @ W2.T.astype(np.int64)
    pred = S.argmax(1)
    truth = (a + b) % p
    top2 = np.sort(S, 1)[:, -2:]
    wrong_mask = pred != truth
    wrong = [(int(x), int(y)) for x, y in zip(a[wrong_mask], b[wrong_mask])]
    gap = top2[:, 1] - top2[:, 0]
    return {
        "wrong_count": int(wrong_mask.sum()),
        "wrong_pairs": wrong,
        "ties": int((top2[:, 0] == top2[:, 1]).sum()),
        "smallest_winning_gap": int(gap[~wrong_mask].min()) if (~wrong_mask).any() else None,
        "largest_weight": int(max(np.abs(E1).max(), np.abs(E2).max(), np.abs(W2).max())),
        "w2_in_fast_range": bool(W2.min() >= -128 and W2.max() <= 127),
        "max_hidden_sum": int(hidden.sum(1).max()),
        "fast_digit_bound_ok": bool(255 * int(hidden.sum(1).max()) < 2 ** 32),
    }


def ns_tag(p, H, seed, frac, wd, steps):
    """A Lean identifier that encodes the configuration, e.g. P7_H8_S0_F0p5_WD1p0_ST3000."""
    def num(x):
        s = f"{x:g}".replace("-", "m").replace(".", "p").replace("+", "")
        return s
    return f"P{p}_H{H}_S{seed}_F{num(frac)}_WD{num(wd)}_ST{steps}"


def write_network(root, lib, name, desc, net_desc, E1, E2, W2, wrong_rows, chunks, p, H, src):
    """Weights, Table, RowsNN and AllInputs for one network, in the style of gen_lean.py.

    `wrong_rows[a]` is the sorted list of b with answer a b != (a + b) % p. Every row theorem
    says: for every b < p, the fast evaluator's checks pass and its answer equals (a + b) % p
    exactly when b is not in that row's list.
    """
    ns = f"{lib}.{name}"
    d = root / name
    d.mkdir(parents=True, exist_ok=True)
    k = sum(len(r) for r in wrong_rows)
    (d / "Weights.lean").write_text(f"""import LeanCheckedNetwork.Network

/-!
# Weights of {net_desc}

{p} possible inputs per side, {H} neurons. Row `x` of `E1` is the embedding of the first input
`x`, row `x` of `E2` the embedding of the second input, row `c` of `W2` the read-out weights of
the answer `c`. `.ofNat n` is the integer n and `.negSucc n` is the integer -(n + 1).
Generated by `sweep/run_one.py` from `{src}`. Configuration: {desc}.
-/

set_option maxRecDepth 100000

namespace {ns}

def E1 : List (List Int) := {table(E1)}

def E2 : List (List Int) := {table(E2)}

def W2 : List (List Int) := {table(W2)}

/-- The network's answer for the pair `(a, b)`. -/
def answer (a b : Nat) : Nat := LeanCheckedNetwork.answer E1 E2 W2 a b

/-- Row `a` of this table lists every `b` with `answer a b ≠ (a + b) % {p}`: {k} pairs in all. -/
def wrongRows : List (List Nat) := [
{chr(10).join("  [" + ", ".join(str(b) for b in r) + "]," for r in wrong_rows[:-1])}
  [{", ".join(str(b) for b in wrong_rows[-1])}]]

/-- The pairs the network gets wrong, as an explicit list. -/
def wrongPairs : List (Nat × Nat) := [{", ".join(f"({a}, {b})" for a, r in enumerate(wrong_rows) for b in r)}]

end {ns}
""")
    (d / "Table.lean").write_text(f"""import LeanCheckedNetwork.Fast
import LeanCheckedNetwork.WrongSet
import {ns}.Weights

namespace {ns}

/-- Every read-out row has {H} entries, each in [-128, 127]: the condition the fast evaluator needs. -/
theorem table_ok : tableOk W2 {H} = true := by decide +kernel

/-- The explicit list of wrong pairs is the row-by-row list, flattened. -/
theorem wrongPairs_eq : wrongPairs = rowsToPairs wrongRows 0 := by decide +kernel

/-- How many pairs the list holds. -/
theorem wrongPairs_length : wrongPairs.length = {k} := by decide +kernel

/-- The list is strictly increasing in lexicographic order, so no pair appears twice. -/
theorem wrongPairs_strictLex : strictLex wrongPairs = true := by decide +kernel

theorem wrongPairs_nodup : wrongPairs.Nodup := nodup_of_strictLex _ wrongPairs_strictLex

/-- Every listed pair is an input: both entries below {p}. -/
theorem wrongPairs_in_range :
    wrongPairs.all (fun x => decide (x.1 < {p}) && decide (x.2 < {p})) = true := by decide +kernel

end {ns}
""")
    for i, rs in enumerate(np.array_split(np.arange(p), chunks)):
        body = []
        for a in rs:
            a = int(a)
            body.append(f"""theorem fast_{a} : ∀ b, b < {p} →
    (fastOk E1 E2 {H} {a} b &&
      ((fastAnswer E1 E2 W2 {H} {a} b == ({a} + b) % {p}) == !(wrongRows.getD {a} []).contains b)) = true := by
  decide +kernel

/-- Row {a}: the network answers ({a} + b) % {p} exactly for the b outside row {a} of `wrongRows`. -/
theorem row_{a} : ∀ b, b < {p} → (answer {a} b = ({a} + b) % {p} ↔ b ∉ wrongRows.getD {a} []) := by
  intro b hb
  have h := fast_{a} b hb
  simp only [Bool.and_eq_true, beq_iff_eq] at h
  show LeanCheckedNetwork.answer E1 E2 W2 {a} b = _ ↔ _
  rw [answer_eq_fastAnswer E1 E2 W2 {H} {a} b table_ok h.1]
  exact iff_not_mem_of_beq h.2
""")
        (d / f"Rows{i:02d}.lean").write_text(f"""import {ns}.Table

/-! Rows {int(rs[0])} to {int(rs[-1])} of the addition table, checked by Lean's kernel for all {p} values of `b`. -/

set_option Elab.async false

namespace {ns}

open LeanCheckedNetwork

{chr(10).join(body)}
end {ns}
""")
    cases = "\n".join(f"  | {a}, _ => exact row_{a}" for a in range(p))
    imports = "\n".join(f"import {ns}.Rows{i:02d}" for i in range(chunks))
    corollary = ""
    if k == 0:
        corollary = f"""
/-- The list is empty, so the network is right on every input: `(a + b) % {p}` for all {p * p} pairs. -/
theorem adds_mod_{p} : ∀ a, a < {p} → ∀ b, b < {p} → answer a b = (a + b) % {p} := by
  intro a ha b hb
  exact (answer_iff_not_wrong a ha b hb).mpr (by simp [wrongPairs])
"""
    (d / "AllInputs.lean").write_text(f"""{imports}

/-!
# {net_desc[0].upper() + net_desc[1:]}: wrong on exactly {k} of {p * p} pairs

For every pair `(a, b)` with `a, b < {p}`, the network answers `(a + b) % {p}` if and only if
`(a, b)` is not in `wrongPairs`, a list of {k} pairs.
-/

namespace {ns}

theorem rows : ∀ a, a < {p} → ∀ b, b < {p} → (answer a b = (a + b) % {p} ↔ b ∉ wrongRows.getD a []) := by
  intro a ha
  match a, ha with
{cases}
  | n + {p}, h => exact absurd h (by omega)

theorem answer_iff_not_wrong : ∀ a, a < {p} → ∀ b, b < {p} →
    (answer a b = (a + b) % {p} ↔ (a, b) ∉ wrongPairs) := by
  intro a ha b hb
  rw [wrongPairs_eq, mem_rowsToPairs]
  simp only [Nat.zero_le, true_and, Nat.sub_zero]
  exact rows a ha b hb
{corollary}
end {ns}
""")
    mods = [f"{ns}.Weights", f"{ns}.Table"] + [f"{ns}.Rows{i:02d}" for i in range(chunks)] + [f"{ns}.AllInputs"]
    return mods, k


def run(cmd, cwd, env=None, log=None, timeout=None):
    t0 = time.time()
    r = subprocess.run(cmd, cwd=cwd, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=timeout)
    if log is not None:
        Path(log).write_text(r.stdout)
    return r.returncode, r.stdout, time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("p", type=int)
    ap.add_argument("H", type=int)
    ap.add_argument("seed", type=int)
    ap.add_argument("frac", type=float)
    ap.add_argument("wd", type=float)
    ap.add_argument("steps", type=int)
    ap.add_argument("outdir")
    ap.add_argument("--repo", default=os.environ.get("LCN_REPO", str(HERE.parent)), help="the lean-checked-network checkout")
    ap.add_argument("--lr", type=float, default=1e-2)
    ap.add_argument("--chunks", type=int, default=0, help="row files per network (default: min(p, 16))")
    ap.add_argument("--jobs", type=int, default=2, help="leanchecker replays run at once (about 2 GB each)")
    ap.add_argument("--build-jobs", type=int, default=0,
                    help="cap Lean's parallelism via LEAN_NUM_THREADS (lake has no -j); default: every visible core")
    args = ap.parse_args()
    p, H, seed, frac, wd, steps = args.p, args.H, args.seed, args.frac, args.wd, args.steps
    repo = Path(args.repo).resolve()
    out = Path(args.outdir).resolve()
    out.mkdir(parents=True, exist_ok=True)
    chunks = args.chunks or min(p, 16)
    env = dict(os.environ, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", MKL_NUM_THREADS="1")
    env["PATH"] = str(Path.home() / ".elan" / "bin") + os.pathsep + env.get("PATH", "")
    tag = ns_tag(p, H, seed, frac, wd, steps)
    lib = f"LeanCheckedNetwork.Sweep.{tag}"
    config = {"p": p, "H": H, "seed": seed, "frac": frac, "wd": wd, "steps": steps, "lr": args.lr,
              "chunks": chunks, "namespace": lib}
    result = {"config": config, "stages": {}, "seconds": {}, "ok": False, "failures": []}
    rc, commit, _ = run(["git", "rev-parse", "HEAD"], repo)
    result["repo_commit"] = commit.strip() if rc == 0 else None
    rc, ver, _ = run(["lean", "--version"], out, env=env)
    result["lean_version"] = ver.strip() if rc == 0 else None
    result["lean_toolchain"] = (repo / "lean" / "lean-toolchain").read_text().strip()
    result["host"] = {"cpus": os.cpu_count(), "argv": sys.argv}

    def fail(stage, why):
        result["failures"].append({"stage": stage, "why": why})
        print(f"FAIL [{stage}] {why}", file=sys.stderr)

    def save():
        (out / "result.json").write_text(json.dumps(result, indent=1))

    # 1. train
    trained = out / "trained.npz"
    rc, log, dt = run([sys.executable, str(repo / "train.py"), str(p), str(H), str(seed), str(args.lr), str(wd), str(frac),
                       str(steps), str(trained)], repo, env=env, log=out / "train.log")
    result["seconds"]["train"] = round(dt, 1)
    result["stages"]["train"] = {"exit": rc, "log": "train.log"}
    if rc != 0 or not trained.exists():
        fail("train", f"train.py exit {rc}: {log[-500:]}"); save(); sys.exit(1)

    # 2. circle-only
    circle = out / "circle_only.npz"
    rc, log, dt = run([sys.executable, str(repo / "circle_only.py"), str(trained), str(circle)], repo, env=env, log=out / "circle_only.log")
    result["seconds"]["circle"] = round(dt, 1)
    result["stages"]["circle"] = {"exit": rc, "stdout": log.strip()}
    if rc != 0 or not circle.exists():
        fail("circle", f"circle_only.py exit {rc}: {log[-500:]}"); save(); sys.exit(1)

    # 3. numpy evaluation
    t0 = time.time()
    tn = np.load(trained)
    nets = {"trained": (tn["E1q"], tn["E2q"], tn["W2q"])}
    cn = np.load(circle)
    circle_eval = evaluate(cn["E1q"], cn["E2q"], cn["W2q"])
    circle_info = {"as_written_by_circle_only_py": {k: v for k, v in circle_eval.items() if k != "wrong_pairs"},
                   "rescaled": False, "rescale_factor": None}
    if circle_eval["w2_in_fast_range"] and circle_eval["fast_digit_bound_ok"]:
        nets["circle_only"] = (cn["E1q"], cn["E2q"], cn["W2q"])
        circle_info["note"] = "circle_only.py's tables used as written"
    else:
        # The fast evaluator needs W2 in [-128, 127] and 255 * sum(hidden) < 2^32. Recompute the
        # waves exactly as circle_only.py does, scale all three tables by one factor so the
        # largest entry is 127, then round. This is a different (smaller) circle-only network.
        rc, log, _ = run([sys.executable, str(HERE / "circle_rescale.py"), str(trained), str(out / "circle_only_scaled.npz")],
                         repo, env=env, log=out / "circle_rescale.log")
        if rc != 0:
            fail("circle", f"circle_rescale.py exit {rc}: {log[-500:]}"); save(); sys.exit(1)
        cs = np.load(out / "circle_only_scaled.npz")
        nets["circle_only"] = (cs["E1q"], cs["E2q"], cs["W2q"])
        circle_info["rescaled"] = True
        circle_info["rescale_factor"] = float(cs["factor"])
        circle_info["note"] = ("circle_only.py's tables have an entry outside the fast evaluator's range, so all three "
                               "tables were multiplied by the factor before rounding; the kernel-checked circle-only "
                               "network is this rescaled one, not the one circle_only.py wrote")
    evals = {name: evaluate(*t) for name, t in nets.items()}
    result["seconds"]["numpy"] = round(time.time() - t0, 1)
    result["networks"] = {}
    for name, ev in evals.items():
        entry = {k: v for k, v in ev.items() if k != "wrong_pairs"}
        entry["wrong_pairs"] = ev["wrong_pairs"] if len(ev["wrong_pairs"]) <= 2000 else ev["wrong_pairs"][:2000]
        entry["wrong_pairs_truncated"] = len(ev["wrong_pairs"]) > 2000
        result["networks"][name] = entry
    result["networks"]["circle_only"].update(circle_info)
    for name, ev in evals.items():
        if not ev["w2_in_fast_range"]:
            fail("numpy", f"{name}: W2 outside [-128, 127], the fast evaluator does not apply")
        if not ev["fast_digit_bound_ok"]:
            fail("numpy", f"{name}: 255 * sum(hidden) >= 2^32 for some pair, the fast evaluator does not apply")
    if result["failures"]:
        save(); sys.exit(1)

    # 4. generate the Lean package
    t0 = time.time()
    ldir = out / "lean"
    if ldir.exists():
        shutil.rmtree(ldir)
    (ldir / "LeanCheckedNetwork").mkdir(parents=True)
    for f in ["lakefile.toml", "lean-toolchain"]:
        shutil.copy(repo / "lean" / f, ldir / f)
    for f in ["Network.lean", "Fast.lean"]:
        shutil.copy(repo / "lean" / "LeanCheckedNetwork" / f, ldir / "LeanCheckedNetwork" / f)
    shutil.copy(HERE / "WrongSet.lean", ldir / "LeanCheckedNetwork" / "WrongSet.lean")
    root = ldir / "LeanCheckedNetwork" / "Sweep" / tag
    desc = f"p={p}, H={H}, seed={seed}, training fraction={frac}, weight decay={wd}, steps={steps}"
    modules = ["LeanCheckedNetwork.Network", "LeanCheckedNetwork.Fast", "LeanCheckedNetwork.WrongSet"]
    main_theorems = {}
    for name, net_desc, src in [("Trained", "the trained network, weights frozen to whole numbers", "trained.npz"),
                                ("CircleOnly", "the trained network with every neuron reduced to its main circle wave"
                                 + (" (rescaled)" if circle_info["rescaled"] else ""),
                                 "circle_only_scaled.npz" if circle_info["rescaled"] else "circle_only.npz")]:
        key = "trained" if name == "Trained" else "circle_only"
        E1, E2, W2 = nets[key]
        wrong_rows = [[] for _ in range(p)]
        for a, b in evals[key]["wrong_pairs"]:
            wrong_rows[a].append(b)
        mods, k = write_network(root, lib, name, desc, net_desc, E1, E2, W2, wrong_rows, chunks, p, H, src)
        modules += mods
        main_theorems[key] = [f"{lib}.{name}.answer_iff_not_wrong"] + (
            [f"{lib}.{name}.adds_mod_{p}"] if k == 0
            else [f"{lib}.{name}.wrongPairs_length", f"{lib}.{name}.wrongPairs_nodup", f"{lib}.{name}.wrongPairs_in_range"])
    (ldir / "LeanCheckedNetwork.lean").write_text(f"import {lib}.Trained.AllInputs\nimport {lib}.CircleOnly.AllInputs\n")
    result["seconds"]["gen"] = round(time.time() - t0, 1)
    result["stages"]["gen"] = {"modules": modules, "main_theorems": main_theorems}

    # 5. lake build
    # Lake has no -j flag (Lake/CLI/Help.lean, v4.35.0-rc2); the Lean runtime sizes its task pool from
    # LEAN_NUM_THREADS, else from every visible core (src/runtime/object.cpp). A Modal container
    # requesting 4 cores still sees 20, so an uncapped build runs ~20 Lean processes at ~2 GB each.
    cmd = ["lake", "build", "LeanCheckedNetwork"]
    build_env = dict(env, LEAN_NUM_THREADS=str(args.build_jobs)) if args.build_jobs else env
    rc, log, dt = run(cmd, ldir, env=build_env, log=out / "build.log")
    result["seconds"]["build"] = round(dt, 1)
    build_ok = rc == 0 and "Build completed successfully" in log
    sorry_warnings = log.count("declaration uses 'sorry'") + log.count("declaration uses `sorry`")
    result["stages"]["build"] = {"exit": rc, "completed": build_ok, "warnings": log.count("warning:"),
                                 "sorry_warnings": sorry_warnings,
                                 "errors": [l for l in log.splitlines() if "error" in l][:20]}
    if not build_ok:
        fail("build", f"lake build exit {rc}; see build.log")
    if sorry_warnings:
        fail("build", "a declaration uses sorry")

    # 6. replay every module with leanchecker
    replay = {}
    dt_total = 0.0
    if build_ok:
        pending = list(modules)
        procs = []
        t0 = time.time()
        while pending or procs:
            while pending and len(procs) < args.jobs:
                m = pending.pop(0)
                lg = open(out / f"leanchecker.{m}.log", "w")
                procs.append((m, subprocess.Popen(["lake", "env", "leanchecker", m], cwd=ldir, env=env, stdout=lg, stderr=subprocess.STDOUT), lg, time.time()))
            time.sleep(0.5)
            still = []
            for m, pr, lg, ts in procs:
                if pr.poll() is None:
                    still.append((m, pr, lg, ts))
                else:
                    lg.close()
                    replay[m] = {"exit": pr.returncode, "seconds": round(time.time() - ts, 1)}
            procs = still
        dt_total = time.time() - t0
        bad = [m for m, r in replay.items() if r["exit"] != 0]
        if bad:
            fail("replay", f"leanchecker failed on {bad}")
    result["seconds"]["replay"] = round(dt_total, 1)
    result["stages"]["replay"] = {"ok": sum(1 for r in replay.values() if r["exit"] == 0), "of": len(modules), "modules": replay}

    # 7. axioms
    axioms = {}
    if build_ok:
        src = "import LeanCheckedNetwork\n" + "".join(f"#print axioms {t}\n" for ts in main_theorems.values() for t in ts)
        (out / "axioms.lean").write_text(src)
        rc, log, dt = run(["lake", "env", "lean", str(out / "axioms.lean")], ldir, env=env, log=out / "axioms.log")
        result["seconds"]["axioms"] = round(dt, 1)
        # #print axioms wraps long lists over several lines, so parse the whole output
        axiom_lines = []
        rest = log
        for m in re.finditer(r"'(\S+)' depends on axioms: \[([^\]]*)\]", log, re.S):
            axioms[m.group(1)] = [x.strip() for x in m.group(2).split(",") if x.strip()]
            axiom_lines.append(f"'{m.group(1)}' depends on axioms: [{', '.join(axioms[m.group(1)])}]")
            rest = rest.replace(m.group(0), "")
        for m in re.finditer(r"'(\S+)' does not depend on any axioms", log):
            axioms[m.group(1)] = []
            axiom_lines.append(m.group(0))
            rest = rest.replace(m.group(0), "")
        if rest.strip():
            axioms["_other_output"] = rest.strip()
        for ts in main_theorems.values():
            for t in ts:
                got = axioms.get(t)
                if got is None:
                    fail("axioms", f"no axioms line for {t}: {log[-300:]}")
                elif not set(got) <= set(STANDARD_AXIOMS):
                    fail("axioms", f"{t} depends on {got}, outside {STANDARD_AXIOMS}")
    result["stages"]["axioms"] = {"lines": axiom_lines if build_ok else [], "parsed": axioms, "standard": STANDARD_AXIOMS}

    # 8. scan the whole package for anything that could weaken the check
    hits = []
    for f in sorted(ldir.rglob("*.lean")):
        txt = f.read_text()
        for word in FORBIDDEN:
            for i, line in enumerate(txt.splitlines(), 1):
                if word in line and not line.lstrip().startswith("--") and not line.lstrip().startswith("/-"):
                    # Fast.lean's doc comment mentions no such word; Network.lean neither. Any hit is reported.
                    hits.append({"file": str(f.relative_to(ldir)), "line": i, "word": word.strip(), "text": line.strip()[:120]})
    result["stages"]["scan"] = {"hits": hits}
    if hits:
        fail("scan", f"forbidden words in the package: {hits[:5]}")

    # verdicts: pass only when every kernel-facing stage passed
    kernel_ok = build_ok and all(r["exit"] == 0 for r in replay.values()) and len(replay) == len(modules) \
        and not any(f["stage"] in ("build", "replay", "axioms", "scan") for f in result["failures"])
    result["kernel"] = {}
    for key, name in [("trained", "Trained"), ("circle_only", "CircleOnly")]:
        k = evals[key]["wrong_count"]
        if kernel_ok:
            stmt = (f"right on all {p * p} pairs ({lib}.{name}.adds_mod_{p})" if k == 0
                    else f"wrong on exactly {k} of {p * p} pairs ({lib}.{name}.answer_iff_not_wrong, wrongPairs_length, wrongPairs_nodup, wrongPairs_in_range)")
            result["kernel"][key] = {"status": "pass", "statement": stmt, "wrong_count": k,
                                     "how": "lake build + leanchecker replay of every module + #print axioms"}
        else:
            result["kernel"][key] = {"status": "fail", "statement": None, "wrong_count": k,
                                     "why": "; ".join(f"[{f['stage']}] {f['why']}" for f in result["failures"])}
    result["seconds"]["total"] = round(sum(v for k, v in result["seconds"].items() if k != "total"), 1)
    result["ok"] = not result["failures"]
    save()
    print(json.dumps({"config": config, "kernel": result["kernel"], "seconds": result["seconds"],
                      "axioms": result["stages"]["axioms"]["lines"], "failures": result["failures"]}, indent=1))
    sys.exit(0 if result["ok"] else 1)


