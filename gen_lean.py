"""Write a frozen network into the Lean package, with one theorem per row of the addition table.

Usage: python3 gen_lean.py NETWORK.npz NAME CHUNKS
  NAME   Lean namespace for this network, e.g. Trained or CircleOnly
  CHUNKS number of files the row theorems are split into (Lake checks files in parallel)
"""
import sys
from pathlib import Path
import numpy as np

src, name, chunks = sys.argv[1], sys.argv[2], int(sys.argv[3])
# Only the file name goes into the generated doc comment: Lean block comments nest, so a path that
# contains "/-" (a directory name starting with a dash does it) would open a comment that never closes.
src_label = Path(src).name
net = np.load(src)
p, H = int(net["p"]), int(net["H"])
root = Path("lean/LeanCheckedNetwork") / name
root.mkdir(parents=True, exist_ok=True)

def lit(x):
    """An Int literal written as a constructor, so the kernel does no typeclass unfolding."""
    x = int(x)
    return f"(.ofNat {x})" if x >= 0 else f"(.negSucc {-x - 1})"

def table(m):
    return "[\n" + ",\n".join("  [" + ", ".join(lit(x) for x in row) + "]" for row in m) + "]"

desc = {
    "Trained": "the trained network, weights frozen to whole numbers",
    "CircleOnly": "the trained network with every neuron reduced to its main circle wave",
}.get(name, name)
(root / "Weights.lean").write_text(f"""import LeanCheckedNetwork.Network

/-!
# Weights of {desc}

{p} possible inputs per side, {H} neurons. Row `x` of `E1` is the embedding of the first input
`x`, row `x` of `E2` the embedding of the second input, row `c` of `W2` the read-out weights of
the answer `c`. `.ofNat n` is the integer n and `.negSucc n` is the integer -(n + 1).
Generated by `gen_lean.py` from `{src_label}`.
-/

set_option maxRecDepth 100000

namespace LeanCheckedNetwork.{name}

def E1 : List (List Int) := {table(net["E1q"])}

def E2 : List (List Int) := {table(net["E2q"])}

def W2 : List (List Int) := {table(net["W2q"])}

/-- The network's answer for the pair `(a, b)`. -/
def answer (a b : Nat) : Nat := LeanCheckedNetwork.answer E1 E2 W2 a b

end LeanCheckedNetwork.{name}
""")

# The read-out table check, done once per network.
(root / "Table.lean").write_text(f"""import LeanCheckedNetwork.Fast
import LeanCheckedNetwork.{name}.Weights

namespace LeanCheckedNetwork.{name}

/-- Every read-out row has {H} entries, each in [-128, 127]: the condition the fast evaluator needs. -/
theorem table_ok : tableOk W2 {H} = true := by decide +kernel

end LeanCheckedNetwork.{name}
""")

# Row theorems, grouped into CHUNKS files that Lake checks in parallel. Each row: the kernel
# runs the fast evaluator on every b (one `decide`), and `answer_eq_fastAnswer` turns that into
# the statement about the network itself.
for i, rs in enumerate(np.array_split(np.arange(p), chunks)):
    body = []
    for a in rs:
        a = int(a)
        body.append(f"""theorem fast_{a} : ∀ b, b < {p} →
    (fastOk E1 E2 {H} {a} b && fastAnswer E1 E2 W2 {H} {a} b == ({a} + b) % {p}) = true := by
  decide +kernel

/-- Row {a} of the addition table: the network answers ({a} + b) % {p} for every b. -/
theorem row_{a} : ∀ b, b < {p} → answer {a} b = ({a} + b) % {p} := by
  intro b hb
  have h := fast_{a} b hb
  simp only [Bool.and_eq_true, beq_iff_eq] at h
  show LeanCheckedNetwork.answer E1 E2 W2 {a} b = _
  rw [answer_eq_fastAnswer E1 E2 W2 {H} {a} b table_ok h.1, h.2]
""")
    (root / f"Rows{i:02d}.lean").write_text(f"""import LeanCheckedNetwork.{name}.Table

/-! Rows {int(rs[0])} to {int(rs[-1])} of the addition table, checked by Lean's kernel for all {p} values of `b`. -/

set_option Elab.async false

namespace LeanCheckedNetwork.{name}

open LeanCheckedNetwork

{chr(10).join(body)}
end LeanCheckedNetwork.{name}
""")

cases = "\n".join(f"  | {a}, _ => exact row_{a}" for a in range(p))
imports = "\n".join(f"import LeanCheckedNetwork.{name}.Rows{i:02d}" for i in range(chunks))
(root / "AllInputs.lean").write_text(f"""{imports}

/-!
# {desc[0].upper() + desc[1:]}: right on every input

The network answers `(a + b) % {p}` for all {p * p} pairs `(a, b)`.
-/

namespace LeanCheckedNetwork.{name}

theorem adds_mod_{p} : ∀ a, a < {p} → ∀ b, b < {p} → answer a b = (a + b) % {p} := by
  intro a ha
  match a, ha with
{cases}
  | n + {p}, h => exact absurd h (by omega)

end LeanCheckedNetwork.{name}
""")
print(f"wrote {root}: {chunks} row files, p={p}, H={H}")
